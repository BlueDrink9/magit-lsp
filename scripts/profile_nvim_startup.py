#!/usr/bin/env python3
"""Profile one public-:Magit startup run, per server launch.

The existing `scripts/measure_nvim_startup.py` harness is reused unchanged. It
launches the server named by `$MAGIT_LSP_BIN`, so this runner replaces that
variable with a generated executable wrapper. In the default strace mode the
wrapper records process, file and wait syscalls; in `--mode perf` it records
sampled user-space CPU stacks, inheriting server child Git processes. Each
launch writes a unique artifact under this run's ignored `build/` directory,
and perf runs also get symbolized text report and stack files.
"""
from __future__ import annotations

import json
import os
import re
import shlex
import shutil
import stat
import subprocess
import sys
import time
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

# `measure_nvim_startup.py` runs three fresh Neovim processes per repository
# (fixture and worktree); each one starts exactly one server. Reopen and focus
# cases reuse that server, so this is the number of expected trace files.
EXPECTED_SERVER_LAUNCHES = 6

TRACE_SUFFIX = ".trace"
PERF_SUFFIX = ".data"
PERF_EVENTS = ("cycles:u", "task-clock:u", "cpu-clock:u")
# Non-flat recordings also request user-space call chains; a kernel callchain
# request needs privileges this sandbox denies even when cycles:u is allowed.
PERF_CALLGRAPHS = ("dwarf", "none")
PERF_FREQUENCY = 999
PERF_PROBE_WORKLOAD = "x = 0\nfor i in range(2000000):\n    x += i\n"
SAMPLES_RE = re.compile(r"#\s*Samples:\s*([\d.]+)\s*([KMG]?)")
REPORT_ROW_RE = re.compile(r"^\s*([\d.]+)%\s+(\d+)\s+(.+)$")
SAMPLE_HEADER_RE = re.compile(r"^\s*(\S+)\s+\d+(?:/\d+)?\s+[\d.]+:\s+\d+\s+\S+:")
DURATION_RE = re.compile(r"<(\d+\.\d+)>\s*$")
SYSCALL_RE = re.compile(r"^\s*(\d+)\s+([\d.]+)\s+([A-Za-z_]\w*)\(")
EXECVE_RE = re.compile(r'execve\("([^"]*)"')
PROCESS_NAMES = {
    "execve", "execveat", "clone", "clone3", "fork", "vfork", "wait4",
    "waitid", "waitpid", "exit", "exit_group", "kill", "tkill", "tgkill",
}


def wrapper_source(tracer: str) -> str:
    """Return the generated server wrapper shell script.

    The wrapper reads its output directory and real server path from the
    environment so paths compose without shell-quoting hazards, and creates a
    fresh trace file so concurrent or repeated launches never share one.
    """
    return f"""#!/bin/sh
# Generated by scripts/profile_nvim_startup.py; traces one server launch.
set -eu
dir=${{MAGIT_STARTUP_STRACE_DIR:?}}
server=${{MAGIT_STARTUP_STRACE_SERVER:?}}
trace=$(mktemp "$dir/server-XXXXXX{TRACE_SUFFIX}")
exec {shlex.quote(tracer)} -f -qq -ttt -T -e trace=%process,%file -o "$trace" "$server" "$@"
"""


def preflight(tracer: str, artifact: Path) -> None:
    """Fail fast unless strace can trace a child; record the probe trace."""
    probe = artifact / "preflight.trace"
    result = subprocess.run(
        [tracer, "-f", "-qq", "-o", str(probe), "-e", "trace=%process", "/bin/true"],
        capture_output=True,
        text=True,
    )
    if result.returncode or not probe.is_file() or not probe.stat().st_size:
        detail = (result.stderr or result.stdout).strip()[-1000:]
        raise SystemExit(f"strace is unusable ({tracer}): {detail or 'empty probe trace'}")
    if "execve(" not in probe.read_text(errors="replace"):
        raise SystemExit(f"strace probe produced no execve evidence: {probe}")


def parse_trace(path: Path) -> dict:
    """Summarize one launch's traced syscalls without attributing wall time."""
    durations: dict[str, float] = {}
    counts: dict[str, int] = {}
    execs: list[str] = []
    server_pid: str | None = None
    server_exits = 0
    pids: set[str] = set()
    for line in path.read_text(errors="replace").splitlines():
        match = SYSCALL_RE.match(line)
        if not match:
            continue
        pid = match.group(1)
        server_pid = server_pid or pid
        pids.add(pid)
        name = match.group(3)
        if pid == server_pid and name in ("exit", "exit_group"):
            server_exits += 1
        counts[name] = counts.get(name, 0) + 1
        duration = DURATION_RE.search(line)
        if duration:
            durations[name] = durations.get(name, 0.0) + float(duration.group(1))
        if name in ("execve", "execveat"):
            execs.extend(EXECVE_RE.findall(line))
    git_execs = [path_ for path_ in execs if path_.rsplit("/", 1)[-1] == "git"]
    traced_ms = sum(durations.values()) * 1000.0
    process_calls = sum(counts.get(name, 0) for name in PROCESS_NAMES)
    process_ms = sum(durations.get(name, 0.0) for name in PROCESS_NAMES) * 1000.0
    file_calls = sum(count for name, count in counts.items() if name not in PROCESS_NAMES)
    file_ms = sum(duration for name, duration in durations.items() if name not in PROCESS_NAMES) * 1000.0
    return {
        "trace": path.name,
        "bytes": path.stat().st_size,
        "pids": len(pids),
        "execs": execs,
        "git_execs": len(git_execs),
        "process_calls": process_calls,
        "wait4_calls": counts.get("wait4", 0),
        "wait4_ms": durations.get("wait4", 0.0) * 1000.0,
        "file_calls": file_calls,
        "file_ms": file_ms,
        "traced_ms": traced_ms,
        "process_minus_wait_ms": max(0.0, process_ms - durations.get("wait4", 0.0) * 1000.0),
        "server_exits": server_exits,
        "by_syscall": {name: {"calls": count, "ms": durations.get(name, 0.0) * 1000.0}
                       for name, count in counts.items()},
    }


def has_server_exit(path: Path) -> bool:
    """Cheaply check whether a trace has finished recording its server exit."""
    size = path.stat().st_size
    if not size:
        return False
    with path.open("rb") as handle:
        first = handle.readline().decode(errors="replace").split()
        handle.seek(max(0, size - 65536))
        tail = handle.read().decode(errors="replace")
    if not first:
        return False
    return re.search(rf"^\s*{re.escape(first[0])}\s+[\d.]+\s+exit(_group)?\(", tail, re.MULTILINE) is not None


def settled_traces(artifact: Path, timeout_s: float = 15.0) -> list[Path]:
    """Wait until every launch trace exists and records its server exit."""
    deadline = time.monotonic() + timeout_s
    while True:
        traces = sorted(path for path in artifact.glob(f"server-*{TRACE_SUFFIX}") if path.is_file())
        if len(traces) >= EXPECTED_SERVER_LAUNCHES and all(has_server_exit(path) for path in traces):
            return traces
        if time.monotonic() >= deadline:
            return traces
        time.sleep(0.1)


def validate(profiles: list[dict], min_launches: int) -> None:
    """Reject missing, empty, truncated or non-distinct per-launch traces."""
    if len(profiles) < min_launches:
        raise SystemExit(f"incomplete samples: {len(profiles)} trace files, expected at least {min_launches}")
    names = [profile["trace"] for profile in profiles]
    if len(set(names)) != len(names):
        raise SystemExit(f"trace files are not distinct per launch: {names}")
    for profile in profiles:
        trace = profile["trace"]
        if not profile["bytes"]:
            raise SystemExit(f"empty trace artifact: {trace}")
        if not profile["execs"]:
            raise SystemExit(f"trace {trace} has no execve evidence")
        if not profile["file_calls"]:
            raise SystemExit(f"trace {trace} has no filesystem syscalls")
        if not profile["wait4_calls"]:
            raise SystemExit(f"trace {trace} has no wait4 evidence for child processes")
        if not profile["server_exits"]:
            raise SystemExit(f"trace {trace} has no server exit record; sample is incomplete")


def median(values: list[float]) -> float:
    ordered = sorted(values)
    middle = len(ordered) // 2
    return ordered[middle] if len(ordered) % 2 else (ordered[middle - 1] + ordered[middle]) / 2


def aggregate(profiles: list[dict]) -> dict:
    """Rank traced costs per launch; never sum across overlapping spans."""
    totals: dict[str, list[float]] = {}
    calls: dict[str, list[int]] = {}
    for profile in profiles:
        for name, entry in profile["by_syscall"].items():
            totals.setdefault(name, []).append(entry["ms"])
            calls.setdefault(name, []).append(entry["calls"])
    ranked = sorted(
        ({"syscall": name, "median_ms": median(totals[name]), "median_calls": median(calls[name])}
         for name in totals),
        key=lambda entry: entry["median_ms"],
        reverse=True,
    )[:10]
    return {
        "launches": len(profiles),
        "per_launch_medians": {
            "server_git_execs": median([profile["git_execs"] for profile in profiles]),
            "process_calls": median([profile["process_calls"] for profile in profiles]),
            "file_calls": median([profile["file_calls"] for profile in profiles]),
            "file_ms": median([profile["file_ms"] for profile in profiles]),
            "wait4_calls": median([profile["wait4_calls"] for profile in profiles]),
            "wait4_ms": median([profile["wait4_ms"] for profile in profiles]),
            "traced_ms": median([profile["traced_ms"] for profile in profiles]),
        },
        "ranked_syscalls_by_median_traced_ms": ranked,
        "limitations": [
            "strace adds ptrace and syscall-record overhead; values are not production timings",
            "traced_ms sums per-syscall durations including child processes; wait4 overlaps child work, so it is not wall time",
            "wait4_ms is blocking wait on children, not their CPU time; strace does not measure CPU",
            "endpoint is the harness's visible Head status/window validation, not terminal redraw or first-window creation",
            "debug build, one-file fixture and dirty worktree; filesystem caches are not cold",
            "trace files keep syscall arguments locally in ignored build/ artifacts and are not committed",
        ],
    }


def perf_callchain_args(callgraph: str) -> list[str]:
    """Perf flags requesting user-space stacks; flat mode requests none."""
    if callgraph == "none":
        return []
    return ["--call-graph", callgraph, "--user-callchains"]


def perf_wrapper_source(perf: str, event: str, callgraph: str) -> str:
    """Return a wrapper that samples one server launch and its children."""
    callgraph_arg = "".join(f"{arg} " for arg in perf_callchain_args(callgraph))
    return f"""#!/bin/sh
# Generated by scripts/profile_nvim_startup.py; samples one server launch.
set -eu
dir=${{MAGIT_STARTUP_PERF_DIR:?}}
server=${{MAGIT_STARTUP_PERF_SERVER:?}}
data=$(mktemp "$dir/server-XXXXXX{PERF_SUFFIX}")
exec {shlex.quote(perf)} record --inherit -o "$data" -e {shlex.quote(event)} -F {PERF_FREQUENCY} {callgraph_arg}-- "$server" "$@"
"""


def sample_count(report_text: str) -> int:
    """Read the total sample count from a `perf report --stdio` header."""
    match = SAMPLES_RE.search(report_text)
    if not match:
        return 0
    scale = {"": 1, "K": 1_000, "M": 1_000_000, "G": 1_000_000_000}[match.group(2)]
    return int(round(float(match.group(1)) * scale))


def parse_report_rows(report_text: str) -> list[dict]:
    """Parse `perf report --sort comm,dso,symbol --show-nr-samples` rows."""
    rows = []
    for line in report_text.splitlines():
        match = REPORT_ROW_RE.match(line)
        if not match:
            continue
        fields = re.split(r"\s{2,}", match.group(3).strip())
        if len(fields) < 3:
            continue
        symbol = fields[2].strip()
        rows.append({
            "overhead_pct": float(match.group(1)),
            "samples": int(match.group(2)),
            "comm": fields[0],
            "dso": fields[1],
            "symbol": symbol,
        })
    return rows


def is_server_comm(comm: str) -> bool:
    """Whether a sampled command belongs to the magit-lsp server process."""
    return comm == "magit-lsp" or comm.startswith(("tokio-rt-worker", "notify-rs"))


def is_git_comm(comm: str) -> bool:
    """Whether a sampled command is a child Git process."""
    return comm == "git"


def workload_role(row: dict) -> str:
    """Attribute a sampled row to the server process, child Git, or other."""
    dso = os.path.basename(row["dso"])
    comm = row["comm"]
    if dso == "[unknown]":
        return "other"
    if is_git_comm(comm) or dso == "git":
        return "git"
    if is_server_comm(comm) or dso == "magit-lsp":
        return "server"
    return "other"


def resolved_frame(symbol: str) -> bool:
    """Whether a stack frame names a function instead of a bare address."""
    if not symbol or symbol == "[unknown]":
        return False
    return re.fullmatch(r"(?:0x)?[0-9a-f]+", symbol, re.IGNORECASE) is None


def parse_callchains(script_text: str) -> dict:
    """Count sampled call chains in `perf script` output.

    Each sample header is followed by one frame per line, leaf first; a flat
    sample has a single frame line. Stacks are only claimed when at least two
    frames are present, so an exit-status-0 recording cannot masquerade as
    captured call chains.
    """
    totals = {
        "samples": 0,
        "stacked_samples": 0,
        "server_stacked_samples": 0,
        "git_stacked_samples": 0,
        "server_frames": 0,
        "server_resolved_frames": 0,
        "git_frames": 0,
        "max_depth": 0,
    }
    comm: str | None = None
    frames: list[tuple[str, str]] = []

    def flush() -> None:
        nonlocal comm, frames
        if comm is None:
            return
        totals["samples"] += 1
        totals["max_depth"] = max(totals["max_depth"], len(frames))
        dsos = [os.path.basename(dso) for _, dso in frames]
        has_server = is_server_comm(comm) or "magit-lsp" in dsos
        has_git = is_git_comm(comm) or "git" in dsos
        if len(frames) >= 2:
            totals["stacked_samples"] += 1
            if has_server:
                totals["server_stacked_samples"] += 1
            if has_git:
                totals["git_stacked_samples"] += 1
        if has_server:
            totals["server_frames"] += len(frames)
            totals["server_resolved_frames"] += sum(
                1 for symbol, _ in frames if resolved_frame(symbol))
        if has_git:
            totals["git_frames"] += len(frames)
        comm = None
        frames = []

    for line in script_text.splitlines():
        match = SAMPLE_HEADER_RE.match(line)
        if match and "PERF_RECORD_" not in line:
            flush()
            comm = match.group(1)
            continue
        if comm is None or "PERF_RECORD_" in line:
            continue
        parts = line.strip().split(None, 1)
        if len(parts) == 2 and re.fullmatch(r"[0-9a-f]{6,}", parts[0]):
            body = parts[1]
            symbol, separator, dso = body.rpartition(" (")
            if separator:
                frames.append((symbol.strip(), dso.rstrip(")").strip()))
            else:
                frames.append((body.strip(), ""))
    flush()
    return totals


def count_git_task_events(script_text: str) -> int:
    """Count inherited child Git exec/fork records in `perf script` output."""
    count = 0
    for line in script_text.splitlines():
        if "PERF_RECORD_" not in line:
            continue
        prefix = line.split("[", 1)[0]
        if re.search(r"(^|\s)git(\s|$)", prefix) or "comm: git" in line:
            count += 1
    return count


def count_git_sample_headers(script_text: str) -> int:
    """Count sampled `git` process headers in `perf script` output."""
    count = 0
    for line in script_text.splitlines():
        match = SAMPLE_HEADER_RE.match(line)
        if match and match.group(1) == "git" and "PERF_RECORD_" not in line:
            count += 1
    return count


def symbolized_user_symbol(symbol: str) -> bool:
    """Whether a report symbol is a resolved user-space function name."""
    if "[.]" not in symbol:
        return False
    return not re.search(r"\b0x[0-9a-f]{6,}\b", symbol, re.IGNORECASE)


def perf_permission_hint() -> str:
    """Describe the permissions a denied perf_event_open needs."""
    def read(path: str) -> str:
        try:
            return Path(path).read_text().strip()
        except OSError:
            return "unknown"

    status = ""
    try:
        status = Path("/proc/self/status").read_text()
    except OSError:
        pass
    cap = next((line.split()[1] for line in status.splitlines()
                if line.startswith("CapEff:")), "unknown")
    seccomp = next((line.split()[1] for line in status.splitlines()
                    if line.startswith("Seccomp:")), "unknown")
    paranoid = read("/proc/sys/kernel/perf_event_paranoid")
    return (f"perf_event_open was denied (perf_event_paranoid={paranoid}, "
            f"Seccomp={seccomp}, CapEff={cap}). Sampling needs a host "
            "kernel.perf_event_paranoid setting that allows CPU event access, "
            "CAP_PERFMON or CAP_SYS_ADMIN, and a sandbox/seccomp profile that "
            "allows perf_event_open; no privilege change was attempted.")


def perf_preflight(perf: str, artifact: Path) -> tuple[str, str]:
    """Probe sampling events and call graphs; return a working configuration."""
    probe_dir = artifact / "preflight"
    probe_dir.mkdir()
    attempts: list[str] = []
    for event in PERF_EVENTS:
        for callgraph in PERF_CALLGRAPHS:
            slug = f"{event.replace(':', '-')}-{callgraph}"
            data = probe_dir / f"probe-{slug}{PERF_SUFFIX}"
            command = [perf, "record", "--inherit", "-o", str(data), "-e", event,
                       "-F", str(PERF_FREQUENCY)]
            command += perf_callchain_args(callgraph)
            command += ["--", sys.executable, "-c", PERF_PROBE_WORKLOAD]
            result = subprocess.run(command, capture_output=True, text=True)
            detail = (result.stderr or result.stdout).strip().splitlines()[-6:]
            samples = 0
            chains: dict = {}
            if result.returncode == 0 and data.is_file() and data.stat().st_size:
                report = subprocess.run(
                    [perf, "report", "--stdio", "-i", str(data), "--sort", "comm,dso,symbol",
                     "--show-nr-samples", "--percent-limit", "0", "--no-children", "-g", "none"],
                    capture_output=True,
                    text=True,
                )
                samples = sample_count(report.stdout)
                (probe_dir / f"{data.stem}.report.txt").write_text(report.stdout + report.stderr)
                stacks = subprocess.run(
                    [perf, "script", "-i", str(data)],
                    capture_output=True,
                    text=True,
                )
                chains = parse_callchains(stacks.stdout + stacks.stderr)
                (probe_dir / f"{data.stem}.samples.txt").write_text(stacks.stdout + stacks.stderr)
            attempts.append(
                f"event {event}, callgraph {callgraph}: rc={result.returncode}, "
                f"bytes={data.stat().st_size if data.exists() else 0}, samples={samples}, "
                f"stacked_samples={chains.get('stacked_samples', 0)}, "
                f"max_depth={chains.get('max_depth', 0)}\n"
                + "\n".join(detail)
            )
            if samples and (callgraph == "none" or chains.get("stacked_samples")):
                (probe_dir / "attempts.txt").write_text(
                    "\n\n".join(attempts + [f"selected: event {event}, callgraph {callgraph}"]) + "\n")
                return event, callgraph
    (probe_dir / "attempts.txt").write_text("\n\n".join(attempts) + "\n")
    last = attempts[-1].replace("\n", " | ") if attempts else "no configuration attempted"
    raise SystemExit(
        f"perf cannot record usable CPU samples ({perf}); last attempt: {last}\n"
        f"probe attempts: {probe_dir / 'attempts.txt'}\n"
        + perf_permission_hint()
    )


def settled_perf_data(artifact: Path, timeout_s: float = 15.0) -> list[Path]:
    """Wait for one nonempty data file per fresh server launch."""
    deadline = time.monotonic() + timeout_s
    while True:
        files = sorted(path for path in artifact.glob(f"server-*{PERF_SUFFIX}") if path.is_file())
        if len(files) >= EXPECTED_SERVER_LAUNCHES and all(path.stat().st_size for path in files):
            return files
        if time.monotonic() >= deadline:
            return files
        time.sleep(0.1)


def analyze_perf_launch(perf: str, data: Path) -> dict:
    """Write text reports and summarize one launch's samples by command."""
    profile = {
        "data": data.name,
        "bytes": data.stat().st_size,
        "report": f"{data.stem}.report.txt",
        "samples": f"{data.stem}.samples.txt",
        "report_ok": False,
        "script_ok": False,
        "samples": 0,
        "rows": [],
        "attributed_samples": 0,
        "server_samples": 0,
        "git_samples": 0,
        "other_samples": 0,
        "git_task_events": 0,
        "git_sample_headers": 0,
        "callchains": parse_callchains(""),
    }
    if not profile["bytes"]:
        return profile
    report = subprocess.run(
        [perf, "report", "--stdio", "-i", str(data), "--sort", "comm,dso,symbol",
         "--show-nr-samples", "--percent-limit", "0", "--no-children", "-g", "none"],
        capture_output=True,
        text=True,
    )
    report_text = report.stdout + report.stderr
    data.with_suffix(".report.txt").write_text(report_text)
    stacks = subprocess.run(
        [perf, "script", "-i", str(data), "--show-task-events"],
        capture_output=True,
        text=True,
    )
    stacks_text = stacks.stdout + stacks.stderr
    data.with_suffix(".samples.txt").write_text(stacks_text)
    rows = parse_report_rows(report_text)
    profile.update({
        "report_ok": report.returncode == 0,
        "script_ok": stacks.returncode == 0,
        "samples": sample_count(report_text),
        "rows": rows,
        "attributed_samples": sum(row["samples"] for row in rows),
        "server_samples": sum(row["samples"] for row in rows if workload_role(row) == "server"),
        "git_samples": sum(row["samples"] for row in rows if workload_role(row) == "git"),
        "other_samples": sum(row["samples"] for row in rows if workload_role(row) == "other"),
        "git_task_events": count_git_task_events(stacks_text),
        "git_sample_headers": count_git_sample_headers(stacks_text),
        "callchains": parse_callchains(stacks_text),
    })
    return profile


def validate_perf(profiles: list[dict], min_launches: int, callgraph: str) -> None:
    """Reject unusable recorder output, missing samples or lost children."""
    if len(profiles) < min_launches:
        raise SystemExit(
            f"incomplete samples: {len(profiles)} perf data files, expected at least {min_launches}")
    names = [profile["data"] for profile in profiles]
    if len(set(names)) != len(names):
        raise SystemExit(f"perf data files are not distinct per launch: {names}")
    for profile in profiles:
        name = profile["data"]
        if not profile["bytes"]:
            raise SystemExit(f"empty perf data artifact: {name}")
        if not profile["report_ok"] or not profile["samples"]:
            raise SystemExit(f"perf report for {name} has no usable samples")
        server_rows = [row for row in profile["rows"] if workload_role(row) == "server"]
        if not server_rows:
            raise SystemExit(f"perf data {name} has no samples attributed to the magit-lsp server")
        if not any(symbolized_user_symbol(row["symbol"]) for row in server_rows):
            raise SystemExit(f"perf data {name} has no symbolized server functions")
        if not profile["script_ok"]:
            raise SystemExit(f"perf script failed for {name}")
        if not profile["git_task_events"]:
            raise SystemExit(
                f"perf data {name} has no inherited child Git task events; child recording is not evidenced")
        chains = profile["callchains"]
        if callgraph != "none" and not chains["server_stacked_samples"]:
            raise SystemExit(
                f"perf data {name} recorded call graph {callgraph} but has no server call chains "
                f"({chains['stacked_samples']} stacked samples, "
                f"{chains['server_resolved_frames']} resolved server frames); "
                "flat samples must not be reported as captured stacks")


def aggregate_perf(profiles: list[dict], event: str, callgraph: str) -> dict:
    """Rank sampled symbols by process role and record honest coverage gaps."""
    symbols: dict[tuple[str, str], dict] = defaultdict(lambda: {"samples": 0, "launches": 0})
    for profile in profiles:
        seen: set[tuple[str, str]] = set()
        for row in profile["rows"]:
            key = (workload_role(row), row["symbol"])
            symbols[key]["samples"] += row["samples"]
            if key not in seen:
                symbols[key]["launches"] += 1
                seen.add(key)
    ranked = sorted(
        ({"role": role, "symbol": symbol, **entry} for (role, symbol), entry in symbols.items()),
        key=lambda entry: entry["samples"],
        reverse=True,
    )
    total_samples = sum(profile["attributed_samples"] for profile in profiles)
    for entry in ranked:
        entry["share_pct"] = (100.0 * entry["samples"] / total_samples) if total_samples else 0.0

    def medians(key: str) -> float:
        return median([profile[key] for profile in profiles])

    return {
        "launches": len(profiles),
        "event": event,
        "callgraph": callgraph,
        "frequency_hz": PERF_FREQUENCY,
        "per_launch_medians": {
            "data_bytes": medians("bytes"),
            "samples": medians("samples"),
            "attributed_samples": medians("attributed_samples"),
            "server_samples": medians("server_samples"),
            "git_samples": medians("git_samples"),
            "other_samples": medians("other_samples"),
            "git_task_events": medians("git_task_events"),
            "git_sample_headers": medians("git_sample_headers"),
        },
        "top_server_symbols": [entry for entry in ranked if entry["role"] == "server"][:10],
        "top_git_symbols": [entry for entry in ranked if entry["role"] == "git"][:10],
        "top_symbols": ranked[:15],
        "stack_evidence": {
            "stacked_samples": sum(p["callchains"]["stacked_samples"] for p in profiles),
            "server_stacked_samples": sum(p["callchains"]["server_stacked_samples"] for p in profiles),
            "git_stacked_samples": sum(p["callchains"]["git_stacked_samples"] for p in profiles),
            "server_resolved_frames": sum(p["callchains"]["server_resolved_frames"] for p in profiles),
            "max_depth": max((p["callchains"]["max_depth"] for p in profiles), default=0),
        },
        "limitations": [
            "CPU samples are a statistical share of on-CPU cycles, not wall/elapsed time or wait time",
            "short child Git processes may record task events without enough samples for a representative hotspot",
            f"call graph is {callgraph}; " + (
                "flat samples only, so no stack attribution is available"
                if callgraph == "none"
                else "user-space (--user-callchains) stacks; inclusive frames overlap and must not be added across functions"),
            "perf sampling and the debug build add overhead and bias values",
            "endpoint is the harness's visible Head status/window validation, not terminal redraw or first-window creation",
            "three launches per repository; one-file fixture and dirty worktree are not controlled production baselines",
            "raw perf data and text reports remain in ignored build/ artifacts and are not committed",
        ],
    }


def main_perf() -> int:
    """Run the unchanged harness with perf-attached server launches."""
    repo = Path(__file__).resolve().parents[1]
    real_server = Path(os.environ.get("MAGIT_LSP_BIN", str(repo / "target/debug/magit-lsp")))
    if not real_server.is_file():
        raise SystemExit(f"server binary missing: {real_server} (run make build)")
    perf = shutil.which("perf")
    if not perf:
        raise SystemExit("perf is not available on PATH; cannot capture CPU samples")

    artifact = repo / "build/startup-perf" / f"{datetime.now(timezone.utc):%Y%m%dT%H%M%S}-{os.getpid()}"
    artifact.mkdir(parents=True, exist_ok=False)
    event, callgraph = perf_preflight(perf, artifact)

    wrapper = artifact / "server-wrapper.sh"
    wrapper.write_text(perf_wrapper_source(perf, event, callgraph))
    wrapper.chmod(wrapper.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    env = os.environ.copy()
    env.update(
        MAGIT_LSP_BIN=str(wrapper),
        MAGIT_STARTUP_PERF_DIR=str(artifact),
        MAGIT_STARTUP_PERF_SERVER=str(real_server),
    )
    measured = subprocess.run(
        [sys.executable, str(repo / "scripts/measure_nvim_startup.py")],
        cwd=repo,
        env=env,
        text=True,
        capture_output=True,
        timeout=600,
    )
    (artifact / "measure.stdout").write_text(measured.stdout)
    (artifact / "measure.stderr").write_text(measured.stderr)
    if measured.returncode:
        print(measured.stderr[-2000:], file=sys.stderr)
        print(f"startup measurement failed ({measured.returncode}); data: {artifact}", file=sys.stderr)
        return measured.returncode

    data_files = settled_perf_data(artifact)
    profiles = [analyze_perf_launch(perf, path) for path in data_files]
    validate_perf(profiles, EXPECTED_SERVER_LAUNCHES, callgraph)
    summary = {
        "server": str(real_server),
        "perf": perf,
        "perf_version": subprocess.check_output([perf, "--version"], text=True).strip(),
        "artifact": str(artifact.relative_to(repo)),
        "aggregate": aggregate_perf(profiles, event, callgraph),
        "launches": [dict(profile, rows=profile["rows"][:50]) for profile in profiles],
    }
    (artifact / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")

    medians = summary["aggregate"]["per_launch_medians"]
    print(f"sampled server launches: {len(profiles)} (from {EXPECTED_SERVER_LAUNCHES} expected fresh processes)")
    print(f"recorder: event={event}, callgraph={callgraph}, frequency={PERF_FREQUENCY} Hz")
    print("per-launch median: "
          f"samples={medians['samples']:g}, data={medians['data_bytes'] / 1024:.1f} KiB, "
          f"Git task events={medians['git_task_events']:g}, "
          f"Git sample headers={medians['git_sample_headers']:g}")
    stacks = summary["aggregate"]["stack_evidence"]
    git_gap = not any(profile["rows"] and any(row["comm"] == "git" for row in profile["rows"])
                      for profile in profiles)
    if callgraph == "none":
        print("call graph probe failed (see "
              f"{artifact.relative_to(repo)}/preflight/attempts.txt); reporting flat symbolized hotspots")
    else:
        print("call chains: "
              f"stacked samples={stacks['stacked_samples']}, "
              f"server stacked={stacks['server_stacked_samples']}, "
              f"Git stacked={stacks['git_stacked_samples']}, "
              f"resolved server frames={stacks['server_resolved_frames']}, "
              f"max depth={stacks['max_depth']}")
    print("top sampled server functions by CPU share:")
    for entry in summary["aggregate"]["top_server_symbols"]:
        print(f"  {entry['symbol']:<52} {entry['share_pct']:6.2f}%  samples={entry['samples']}")
    print("top sampled Git functions by CPU share:" if not git_gap
          else "Git CPU samples: none recorded (task events prove inheritance; processes were too short to sample)")
    for entry in summary["aggregate"]["top_git_symbols"]:
        print(f"  {entry['symbol']:<52} {entry['share_pct']:6.2f}%  samples={entry['samples']}")
    print(f"artifacts: {artifact.relative_to(repo)} (summary.json, per-launch .data, .report.txt, .samples.txt)")
    return 0


def main() -> int:
    if sys.argv[1:] == ["--mode", "perf"]:
        return main_perf()
    if sys.argv[1:]:
        raise SystemExit(f"usage: {sys.argv[0]} [--mode strace|perf]")
    return main_strace()


