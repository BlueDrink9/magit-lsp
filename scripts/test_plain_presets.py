#!/usr/bin/env python3
"""Exercise Plain LSP capability presets in isolated child Neovim processes."""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import signal
import tempfile
import time
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRESETS = {
    "minimal": {"workspace": {"applyEdit": True}, "textDocument": {"codeAction": {}}},
    "showDocument": {"workspace": {"applyEdit": True}, "textDocument": {"codeAction": {}}, "window": {"showDocument": {"support": True}}},
    "completion": {"workspace": {"applyEdit": True}, "textDocument": {"codeAction": {}, "completion": {"completionItem": {"snippetSupport": True}}}},
    "progress": {"workspace": {"applyEdit": True}, "textDocument": {"codeAction": {}}, "window": {"workDoneProgress": True}},
    "full": {"workspace": {"applyEdit": True, "workspaceEdit": {"documentChanges": True}}, "textDocument": {"codeAction": {}, "completion": {"completionItem": {"snippetSupport": True}}}, "window": {"showDocument": {"support": True}, "workDoneProgress": True}},
}


def teardown(child: subprocess.Popen[bytes], deadline_seconds: float = 5) -> None:
    """Stop and reap an editor and every process in its owned session."""
    pgid = child.pid
    deadline = time.monotonic() + deadline_seconds
    errors = []
    try:
        os.killpg(pgid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    while time.monotonic() < deadline:
        try:
            os.killpg(pgid, 0)
        except ProcessLookupError:
            break
        time.sleep(min(.02, max(0, deadline - time.monotonic())))
    try:
        os.killpg(pgid, 0)
    except ProcessLookupError:
        pass
    else:
        os.killpg(pgid, signal.SIGKILL)
    try:
        child.wait(timeout=max(.01, deadline_seconds))
    except subprocess.TimeoutExpired:
        errors.append("editor child was not reaped")
    try:
        os.killpg(pgid, 0)
    except ProcessLookupError:
        pass
    else:
        errors.append("owned process group remains alive")
    if errors:
        raise RuntimeError("; ".join(errors))


def teardown_preserving_primary(
    child: subprocess.Popen[bytes], primary: BaseException | None
) -> None:
    """Tear down the child without replacing an already-active failure."""
    try:
        teardown(child)
    except Exception as cleanup_error:
        if primary is None:
            raise
        primary.add_note(f"process cleanup also failed: {cleanup_error}")
        raise primary


def table() -> str:
    rows = ["<!-- Generated by `make update-capability-presets`; do not edit. -->",
            "# What you get for what you declare", "",
            "Native coverage: `make plain-presets` runs five isolated child Neovim clients with no plugin or tmux. "
            "Every preset declares applyEdit + codeAction and verifies actual initialize declarations, status rendering, "
            "draft attachment/didOpen, didChange version synchronization, cancellation, restored status, preserved unsaved draft text, "
            "unchanged HEAD/index/status/worktree and graceful client shutdown. "
            "The strict fake-editor lattice separately checks undeclared wire features; Neovim alone cannot prove their absence.", "",
            "| Preset | Declared optional capabilities | Observed workflow |", "|---|---|---|"]
    labels = {"showDocument": "window.showDocument", "completion": "textDocument.completion", "progress": "window.workDoneProgress", "full": "showDocument, completion, progress, documentChanges"}
    results = {
        "minimal": "Readable manual-open fallback; document Abort acknowledged; no progress events",
        "showDocument": "Native showDocument opens Git draft; document Abort acknowledged; no progress events",
        "completion": "Manual-open fallback and document Abort; client declares completion but server has no completionProvider (no completion offered)",
        "progress": "Manual-open fallback; native progress create/begin, client cancellation and progress end",
        "full": "Native showDocument opens Git draft; native progress create/begin, client cancellation and progress end; completion declared but no server completionProvider",
    }
    for name in PRESETS:
        optional = labels.get(name, "None beyond minimum (applyEdit + codeAction)")
        rows.append(f"| `{name}` | {optional} | {results[name]} |")
    return "\n".join(rows) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--binary", type=Path, default=Path(os.environ.get("MAGIT_LSP_BIN", ROOT / "target/debug/magit-lsp")))
    args = parser.parse_args()
    if args.generate:
        out = ROOT / "docs/schema/capability-presets.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(table())
        return
    if not args.binary.exists():
        raise SystemExit(f"missing server binary: {args.binary}")
    for preset, capabilities in PRESETS.items():
        with tempfile.TemporaryDirectory(prefix=f"plain-{preset}-") as td:
            root = Path(td)
            repo = root / "repo"
            repo.mkdir()
            env = os.environ | {"HOME": str(root), "PLAIN_REPO": str(repo), "PLAIN_SERVER": str(args.binary), "PLAIN_PRESET": preset, "PLAIN_RESULT": str(root / "result.json"), "GIT_CONFIG_NOSYSTEM": "1"}
            def git(*cmd: str) -> None:
                subprocess.run(["git", *cmd], cwd=repo, env=env, check=True, stdout=subprocess.DEVNULL)
            git("init", "-q"); git("config", "user.name", "Preset Test"); git("config", "user.email", "preset@example.invalid")
            (repo / "tracked.txt").write_text("initial\n"); git("add", "tracked.txt"); git("commit", "-qm", "initial")
            (repo / "tracked.txt").write_text("initial\nchanged\n")
            git("add", "tracked.txt")
            (repo / ".git/COMMIT_EDITMSG").unlink()
            def snapshot() -> list[str]:
                return [subprocess.check_output(["git", *cmd], cwd=repo, env=env, text=True) for cmd in
                        [("rev-parse", "HEAD"), ("write-tree",), ("status", "--porcelain")]] + [(repo / "tracked.txt").read_text()]
            before = snapshot()
            child = subprocess.Popen(["nvim", "--headless", "--noplugin", "-u", str(ROOT / "tests/ui/plain-presets/init.lua")], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, start_new_session=True)
            try:
                deadline = time.monotonic() + 90
                result_file = root / "result.json"
                while time.monotonic() < deadline and not result_file.exists() and child.poll() is None:
                    time.sleep(.1)
                if not result_file.exists():
                    raise AssertionError(f"{preset}: child Neovim did not report native document behavior")
                result = json.loads(result_file.read_text())
                assert "error" not in result, (preset, result)
                actual = result["capabilities"]
                expected = json.loads(json.dumps(capabilities))
                if expected.get("textDocument", {}).get("codeAction") == {}:
                    expected["textDocument"]["codeAction"] = []
                assert actual == expected, (preset, result)
                assert result["uri"].endswith("/.magit") and "Head:" in result["text"], (preset, result)
                assert result["client_version"] is not None and result["stopped"], (preset, result)
                assert not result["project_modules"] and result["draft_text"].startswith("Native draft edit\n"), (preset, result)
                assert snapshot() == before, (preset, "cancel changed Git state")
                child.wait(timeout=5)
                assert child.returncode == 0, (preset, child.stderr.read().decode())
                print(f"PASS {preset}: native status/draft, user edit synchronization, cancel restores document and Git state, clean shutdown")
            finally:
                primary = sys.exc_info()[1]
                teardown_preserving_primary(child, primary)


if __name__ == "__main__":
    main()
